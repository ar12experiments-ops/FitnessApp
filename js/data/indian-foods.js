export function getFoodById(id) {
  return INDIAN_FOOD_DATABASE.find(f => f.id === id);
}

export function filterFoods({ regionalType, dietType, category, query }) {
  return INDIAN_FOOD_DATABASE.filter(food => {
    if (regionalType && !food.regional_type.includes(regionalType)) return false;
    if (dietType && !food.diet_type.includes(dietType)) return false;
    if (category && food.category !== category) return false;
    if (query) {
      const q = query.toLowerCase();
      const matchName = food.name.toLowerCase().includes(q);
      const matchMicros = food.micros.toLowerCase().includes(q);
      if (!matchName && !matchMicros) return false;
    }
    return true;
  });
}
